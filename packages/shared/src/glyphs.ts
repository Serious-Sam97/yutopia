/** A sign's words as the face can draw them: capitals, what it has glyphs for, spaces run together,
 *  at most `max` long. */
export function cleanText(s: unknown, max: number): string {
  if (typeof s !== "string") return "";
  let out = "";
  for (const ch of s.toUpperCase().replace(/\s+/g, " ")) {
    if (out.length >= max) break;
    if (GLYPHS[ch]) out += ch;
  }
  return out.trim();
}

/** The dots a glyph lights: [column 0–4, row 0–6 from the top]. */
export function glyphDots(ch: string): [number, number][] {
  const g = GLYPHS[ch] ?? GLYPHS["?"];
  const out: [number, number][] = [];
  for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r] & (0x10 >> c)) out.push([c, r]);
  return out;
}
